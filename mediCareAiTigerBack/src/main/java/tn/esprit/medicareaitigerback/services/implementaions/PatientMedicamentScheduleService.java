package tn.esprit.medicareaitigerback.services.implementaions;

import lombok.AllArgsConstructor;
import org.springframework.stereotype.Service;
import tn.esprit.medicareaitigerback.models.dto.request.CreatePatientMedicamentScheduleDTO;
import tn.esprit.medicareaitigerback.models.dto.response.PatientMedicamentScheduleResponseDTO;
import tn.esprit.medicareaitigerback.models.entities.Medicament;
import tn.esprit.medicareaitigerback.models.entities.Patient;
import tn.esprit.medicareaitigerback.models.entities.PatientMedicamentSchedule;
import tn.esprit.medicareaitigerback.repositories.MedicamentRepository;
import tn.esprit.medicareaitigerback.repositories.PatientMedicamentAlertRepository;
import tn.esprit.medicareaitigerback.repositories.PatientMedicamentScheduleRepository;
import tn.esprit.medicareaitigerback.repositories.PatientRepository;
import tn.esprit.medicareaitigerback.services.interfaces.IPatientMedicamentScheduleService;

import java.time.LocalDate;
import java.time.LocalTime;
import java.util.List;
import java.util.stream.Collectors;

@Service
@AllArgsConstructor
public class PatientMedicamentScheduleService implements IPatientMedicamentScheduleService {

    private final PatientMedicamentScheduleRepository scheduleRepository;
    private final MedicamentRepository medicamentRepository;
    private final PatientRepository patientRepository;
    private final PatientMedicamentAlertRepository alertRepository;

    // Default duration if doctor doesn't provide an end date
    private static final int DEFAULT_DURATION_DAYS = 30;

    @Override
    public PatientMedicamentScheduleResponseDTO create(Long patientId, CreatePatientMedicamentScheduleDTO dto) {
        Patient patient = patientRepository.findById(patientId).orElseThrow(() -> new IllegalStateException("Patient not found: " + patientId));
        Medicament medicament = medicamentRepository.findById(dto.getMedicamentId()).orElseThrow(() -> new IllegalStateException("Medicament not found: " + dto.getMedicamentId()));

        LocalDate startDate = dto.getStartDate();
        LocalDate endDate = dto.getEndDate() != null ? dto.getEndDate() : startDate.plusDays(DEFAULT_DURATION_DAYS);
        if (endDate.isBefore(startDate)) {
            throw new IllegalStateException("endDate must be >= startDate");
        }

        PatientMedicamentSchedule schedule = new PatientMedicamentSchedule();
        schedule.setPatient(patient);
        schedule.setMedicament(medicament);
        schedule.setDose(dto.getDose().trim());
        schedule.setStartDate(startDate);
        schedule.setEndDate(endDate);
        schedule.setAlertBeforeMinutes(dto.getAlertBeforeMinutes());
        schedule.setDaysOfWeek(dto.getDaysOfWeek());
        schedule.setTimesOfDay(parseTimes(dto.getTimesOfDay()));

        PatientMedicamentSchedule saved = scheduleRepository.save(schedule);
        return toDTO(saved);
    }

    @Override
    @org.springframework.transaction.annotation.Transactional
    public PatientMedicamentScheduleResponseDTO edit(Long scheduleId, CreatePatientMedicamentScheduleDTO dto) {
        PatientMedicamentSchedule schedule = scheduleRepository.findById(scheduleId).orElseThrow(() -> new IllegalStateException("Schedule not found: " + scheduleId));

        Medicament medicament = medicamentRepository.findById(dto.getMedicamentId())
                .orElseThrow(() -> new IllegalStateException("Medicament not found: " + dto.getMedicamentId()));

        LocalDate startDate = dto.getStartDate();
        LocalDate endDate = dto.getEndDate() != null ? dto.getEndDate() : startDate.plusDays(DEFAULT_DURATION_DAYS);
        if (endDate.isBefore(startDate)) {
            throw new IllegalStateException("endDate must be >= startDate");
        }

        schedule.setMedicament(medicament);
        schedule.setDose(dto.getDose().trim());
        schedule.setStartDate(startDate);
        schedule.setEndDate(endDate);
        schedule.setAlertBeforeMinutes(dto.getAlertBeforeMinutes());
        schedule.setDaysOfWeek(dto.getDaysOfWeek());
        schedule.setTimesOfDay(parseTimes(dto.getTimesOfDay()));

        // Alerts are generated by the scheduler; when schedule changes, remove existing alerts for this schedule
        alertRepository.deleteBySchedule_Id(schedule.getId());

        PatientMedicamentSchedule saved = scheduleRepository.save(schedule);
        return toDTO(saved);
    }

    @Override
    @org.springframework.transaction.annotation.Transactional
    public void delete(Long scheduleId) {
        if (!scheduleRepository.existsById(scheduleId)) {
            throw new IllegalStateException("Schedule not found: " + scheduleId);
        }
        alertRepository.deleteBySchedule_Id(scheduleId);
        scheduleRepository.deleteById(scheduleId);
    }

    @Override
    public List<PatientMedicamentScheduleResponseDTO> findByPatient(Long patientId) {
        return scheduleRepository
                .findByPatient_IdAndEndDateGreaterThanEqual(patientId, LocalDate.now())
                .stream().map(this::toDTO).collect(Collectors.toList());
    }

    private List<LocalTime> parseTimes(List<String> times) {
        return times.stream()
                .map(String::trim)
                .filter(s -> !s.isEmpty())
                .map(LocalTime::parse) // expects "HH:mm"
                .collect(Collectors.toList());
    }

    private PatientMedicamentScheduleResponseDTO toDTO(PatientMedicamentSchedule schedule) {
        List<String> times = schedule.getTimesOfDay().stream().map(LocalTime::toString).collect(Collectors.toList());
        return new PatientMedicamentScheduleResponseDTO(
                schedule.getId(),
                schedule.getPatient().getId(),
                schedule.getMedicament().getId(),
                schedule.getDose(),
                schedule.getStartDate(),
                schedule.getEndDate(),
                schedule.getAlertBeforeMinutes(),
                schedule.getDaysOfWeek(),
                times
        );
    }
}

